"""Closed routing vocabulary; user/model text is never an executable tool name."""

from enum import StrEnum


class AgentAction(StrEnum):
    LIST_EXPECTATIONS = "LIST_EXPECTATIONS"
    GET_EXPECTATION = "GET_EXPECTATION"
    COMPILE_EXPECTATION = "COMPILE_EXPECTATION"
    CONTINUE_CLARIFICATION = "CONTINUE_CLARIFICATION"
    CAPTURE_EXPECTATION = "CAPTURE_EXPECTATION"
    EXPLAIN_MISMATCH = "EXPLAIN_MISMATCH"
    CANCEL = "CANCEL"
    UNKNOWN = "UNKNOWN"


class CapabilityTool(StrEnum):
    LIST = "list_expectations"
    GET = "get_expectation"
    COMPILE = "compile_expectation"
    CONTINUE = "continue_expectation_compilation"
    CAPTURE = "capture_expectation"
    EXPLAIN = "explain_expectation_mismatch"


class ReasonCode(StrEnum):
    LIST_REQUEST = "LIST_REQUEST"
    DETAIL_REQUEST = "DETAIL_REQUEST"
    CAPTURE_INTENT = "CAPTURE_INTENT"
    FOLLOW_UP = "FOLLOW_UP"
    COMPILED_READY = "COMPILED_READY"
    WHY_QUESTION = "WHY_QUESTION"
    CANCEL_REQUEST = "CANCEL_REQUEST"
    MISSING_REFERENCE = "MISSING_REFERENCE"
    AMBIGUOUS_REFERENCE = "AMBIGUOUS_REFERENCE"
    RESOLUTION_LIMIT = "RESOLUTION_LIMIT"
    NO_ACTIVE_CLARIFICATION = "NO_ACTIVE_CLARIFICATION"
    UNSUPPORTED_REQUEST = "UNSUPPORTED_REQUEST"
    POLICY_REJECTED = "POLICY_REJECTED"


class AgentStatus(StrEnum):
    SUCCESS = "SUCCESS"
    CLARIFICATION = "CLARIFICATION"
    CANCELLED = "CANCELLED"
    UNSUPPORTED = "UNSUPPORTED"
    REJECTED = "REJECTED"
    FAILED = "FAILED"
    DISAMBIGUATION_REQUIRED = "DISAMBIGUATION_REQUIRED"


class FailureCode(StrEnum):
    UNAUTHORIZED = "UNAUTHORIZED"
    NOT_FOUND = "NOT_FOUND"
    INVALID_REQUEST = "INVALID_REQUEST"
    STATE_REJECTED = "STATE_REJECTED"
    UNAVAILABLE = "UNAVAILABLE"
    INTELLIGENCE_UNAVAILABLE = "INTELLIGENCE_UNAVAILABLE"
    PROTOCOL_ERROR = "PROTOCOL_ERROR"
